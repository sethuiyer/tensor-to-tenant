def _quote(value: str) -> str:
    escaped = (
        value.replace("\\", "\\\\")
        .replace("'", "\\'")
        .replace("\r", "\\r")
        .replace("\n", "\\n")
        .replace("\t", "\\t")
    )
    return "'" + escaped + "'"


def _js(value: Any, indent: int = 0) -> str:
    if value is None:
        return "null"
    if value is True:
        return "true"
    if value is False:
        return "false"
    if isinstance(value, str):
        return _quote(value)
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, list):
        if not value:
            return "[]"
        rendered = [_js(item, indent + 2) for item in value]
        # Keep simple object arrays readable and stable, one item per line.
        if all(len(item) < 240 and "\n" not in item for item in rendered):
            return "[" + ", ".join(rendered) + "]"
        pad = " " * (indent + 2)
        close = " " * indent
        return "[\n" + "\n".join(f"{pad}{item}," for item in rendered) + f"\n{close}]"
    if isinstance(value, dict):
        if not value:
            return "{}"
        rendered = [f"{key}: {_js(item, indent + 2)}" for key, item in value.items()]
        if all(len(item) < 240 and "\n" not in item for item in rendered):
            return "{ " + ", ".join(rendered) + " }"
        pad = " " * (indent + 2)
        close = " " * indent
        return "{\n" + "\n".join(f"{pad}{item}," for item in rendered) + f"\n{close}}}"
    raise GenerationError(f"cannot render value of type {type(value).__name__}")


def _render_module(path: Path, values: dict[str, Any]) -> str:
    original = path.read_text(encoding="utf-8")
    declarations = _const_expressions(original)
    replacements: list[tuple[int, int, str]] = []
    current_values = _literal_values(original)
    for name, value in values.items():
        declaration = declarations.get(name)
        if declaration is None:
            continue
        start, end, expression = declaration
        if not expression.startswith(("[", "{")):
            continue
        # Avoid churn when the schema and the current view are already equal.
        if current_values.get(name) == value:
            continue
        replacements.append((start, end, _js(value)))

    rendered = original
    for start, end, replacement in reversed(replacements):
        rendered = rendered[:start] + replacement + rendered[end:]
    if not rendered.startswith(GENERATED_HEADER):
        rendered = GENERATED_HEADER + rendered
    return rendered


