"""Generate the website and cookiecutter curriculum views from ``schema/``.

The YAML entity files are the human-maintained source of truth.  The small
``schema/source_data.yaml`` snapshot carries fields that pre-date the schema
migration (for example the bridge prose and the interview side lanes); it is
also generated and is never edited by hand.  This module deliberately keeps
its parser/renderer dependency-free apart from PyYAML so it can run before the
Astro toolchain is installed.

Usage::

    python tools/generate.py          # write generated views
    python tools/generate.py --check  # fail if a write would be required

The renderer preserves the existing TypeScript interfaces, functions, and
comments, replacing only literal ``export const`` values.  This makes a
schema edit produce a small, reviewable diff while guaranteeing deterministic
output on the next run.
"""

