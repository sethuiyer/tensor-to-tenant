        if not isinstance(targets, list):
            return
        by_key = {str(item.get(key)): item for item in targets if isinstance(item, dict) and item.get(key) is not None}
        for row in rows:
            source_key = row.get("id")
            if source_key is None:
                continue
            source_key = str(source_key)
            target = by_key.get(source_key)
            if target is None:
                continue
            for source_field, target_field in fields.items():
                if source_field in row and row[source_field] is not None:
                    target[target_field] = row[source_field]

