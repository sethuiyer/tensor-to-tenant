def _generated_paths() -> list[Path]:
    return sorted(DATA_DIR.glob("*.ts")) + [GENERATED_HOOK, TEMPLATE_GENERATED_HOOK]


def _hash_outputs() -> dict[str, dict[str, Any]]:
    files: dict[str, dict[str, Any]] = {}
    for path in _generated_paths():
        if not path.exists():
            raise GenerationError(f"missing generated output: {path.relative_to(REPO_ROOT)}")
        payload = path.read_bytes()
        files[str(path.relative_to(REPO_ROOT))] = {
            "sha256": hashlib.sha256(payload).hexdigest(),
            "bytes": len(payload),
        }
    return {"algorithm": "sha256", "files": files}


def _write_hash_manifest() -> None:
    HASH_MANIFEST.write_text(
        json.dumps(_hash_outputs(), indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )


def _check_hash_manifest() -> None:
    if not HASH_MANIFEST.exists():
        raise GenerationError(f"missing {HASH_MANIFEST.relative_to(REPO_ROOT)}")
    try:
        expected = json.loads(HASH_MANIFEST.read_text(encoding="utf-8"))
    except json.JSONDecodeError as error:
        raise GenerationError(f"invalid {HASH_MANIFEST.relative_to(REPO_ROOT)}: {error}") from error
    actual = _hash_outputs()
    if expected != actual:
        raise GenerationError("generated_hashes.json does not match generated outputs")


