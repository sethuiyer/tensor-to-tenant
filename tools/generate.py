def generate(*, check: bool = False) -> list[Path]:
    _validate_curriculum_schema()
    source = _source_data()
    effective = _apply_schema_overrides(source)
    cookie = _load_yaml(COOKIECUTTER_SCHEMA)
    changed: list[Path] = []

    for module, values in sorted(effective.items()):
        path = DATA_DIR / f"{module}.ts"
        if not path.exists():
            continue
        rendered = _render_module(path, values)
        current = path.read_text(encoding="utf-8")
        if rendered != current:
            changed.append(path)
            if not check:
                path.write_text(rendered, encoding="utf-8")

    hook_rendered = _render_hook_module(_hook_values(effective, cookie))
    for hook_path in (GENERATED_HOOK, TEMPLATE_GENERATED_HOOK):
        current_hook = hook_path.read_text(encoding="utf-8") if hook_path.exists() else ""
        if hook_rendered != current_hook:
            changed.append(hook_path)
            if not check:
                hook_path.parent.mkdir(parents=True, exist_ok=True)
                hook_path.write_text(hook_rendered, encoding="utf-8")

    return changed


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="report drift without writing files")
    parser.add_argument(
        "--update-hashes",
        action="store_true",
        help="write tools/generated_hashes.json after generating outputs",
    )
    args = parser.parse_args(argv)
    if args.check and args.update_hashes:
        parser.error("--check and --update-hashes are mutually exclusive")
    try:
        changed = generate(check=args.check)
        if args.check and not changed:
            _check_hash_manifest()
    except (OSError, GenerationError, yaml.YAMLError) as error:
        print(f"generate.py: error: {error}", file=sys.stderr)
        return 1
    if args.update_hashes:
        _write_hash_manifest()
    if changed:
        action = "would update" if args.check else "updated"
        print(f"generate.py: {action} {len(changed)} file(s):")
        for path in changed:
            print(f"  - {path.relative_to(REPO_ROOT)}")
        return 1 if args.check else 0
    print("generate.py: generated views are up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
