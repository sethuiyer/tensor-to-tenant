def _week_range(value: str) -> tuple[int, int]:
    numbers = [int(number) for number in re.findall(r"\d+", str(value))]
    if len(numbers) < 2:
        raise GenerationError(f"invalid week range: {value!r}")
    return numbers[0], numbers[1]


def _python(value: Any) -> str:
    return pprint.pformat(value, width=110, sort_dicts=False, compact=False)


def _hook_values(effective: dict[str, dict[str, Any]], cookie: dict[str, Any]) -> dict[str, Any]:
    weeks = effective.get("weeks", {})
    phases = weeks.get("PHASES", [])
    week_rows = weeks.get("WEEKS", [])
