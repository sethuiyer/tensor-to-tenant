class GenerationError(RuntimeError):
    """Raised when the schema cannot produce a safe generated view."""


# ---------------------------------------------------------------------------
# Minimal JavaScript literal parser
# ---------------------------------------------------------------------------
# The data files intentionally contain only JSON-like literals.  Parsing that
# subset here avoids making Node/TypeScript a prerequisite for the generator.


class _JSParser:
    def __init__(self, text: str):
        self.text = text
        self.i = 0
        self.n = len(text)

    def _skip(self) -> None:
        while self.i < self.n:
            if self.text[self.i].isspace():
                self.i += 1
                continue
            if self.text.startswith("//", self.i):
                end = self.text.find("\n", self.i + 2)
                self.i = self.n if end < 0 else end + 1
                continue
            if self.text.startswith("/*", self.i):
                end = self.text.find("*/", self.i + 2)
                if end < 0:
                    raise GenerationError("unterminated JavaScript comment")
                self.i = end + 2
                continue
            break

    def parse(self) -> Any:
        self._skip()
        value = self._value()
        self._skip()
        if self.i != self.n:
            raise GenerationError(f"unexpected JavaScript text at offset {self.i}")
        return value

    def _value(self) -> Any:
        self._skip()
        if self.i >= self.n:
            raise GenerationError("unexpected end of JavaScript literal")
        char = self.text[self.i]
        if char in "'\"":
            return self._string()
        if char == "[":
            return self._array()
        if char == "{":
            return self._object()

        number = re.match(
            r"-?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][+-]?\d+)?",
            self.text[self.i :],
        )
        if number:
            raw = number.group(0)
            self.i += len(raw)
            return float(raw) if any(c in raw for c in ".eE") else int(raw)

        identifier = re.match(r"[A-Za-z_$][\w$]*", self.text[self.i :])
        if identifier:
            raw = identifier.group(0)
            self.i += len(raw)
            return {"true": True, "false": False, "null": None, "undefined": None}.get(raw, raw)
        raise GenerationError(f"unsupported JavaScript literal near {self.text[self.i:self.i + 40]!r}")

    def _string(self) -> str:
        quote = self.text[self.i]
        self.i += 1
        result: list[str] = []
        while self.i < self.n:
            char = self.text[self.i]
            self.i += 1
            if char == quote:
                return "".join(result)
            if char != "\\":
                result.append(char)
                continue
            if self.i >= self.n:
                raise GenerationError("unterminated JavaScript escape")
            escaped = self.text[self.i]
            self.i += 1
            simple = {"n": "\n", "r": "\r", "t": "\t", "b": "\b", "f": "\f", "v": "\v", "0": "\0"}
            if escaped in simple:
                result.append(simple[escaped])
            elif escaped == "u":
                raw = self.text[self.i : self.i + 4]
                if len(raw) != 4 or not re.fullmatch(r"[0-9A-Fa-f]{4}", raw):
                    raise GenerationError("invalid JavaScript unicode escape")
                result.append(chr(int(raw, 16)))
                self.i += 4
            elif escaped == "x":
                raw = self.text[self.i : self.i + 2]
                if len(raw) != 2 or not re.fullmatch(r"[0-9A-Fa-f]{2}", raw):
                    raise GenerationError("invalid JavaScript hex escape")
                result.append(chr(int(raw, 16)))
                self.i += 2
            elif escaped == "\n":
                continue
            else:
                result.append(escaped)
        raise GenerationError("unterminated JavaScript string")

    def _array(self) -> list[Any]:
        self.i += 1  # [
        result: list[Any] = []
        self._skip()
        while self.i < self.n and self.text[self.i] != "]":
            if self.text[self.i] == ",":
                self.i += 1
                self._skip()
                continue
            result.append(self._value())
            self._skip()
            if self.i < self.n and self.text[self.i] == ",":
                self.i += 1
                self._skip()
            elif self.i < self.n and self.text[self.i] != "]":
                raise GenerationError(f"expected comma in array at offset {self.i}")
        if self.i >= self.n:
            raise GenerationError("unterminated JavaScript array")
        self.i += 1
        return result

    def _object(self) -> dict[str, Any]:
        self.i += 1  # {
        result: dict[str, Any] = {}
        self._skip()
        while self.i < self.n and self.text[self.i] != "}":
            if self.text[self.i] in "'\"":
                key = self._string()
            else:
                key_match = re.match(r"[A-Za-z_$][\w$]*", self.text[self.i :])
                if not key_match:
                    raise GenerationError(f"invalid object key at offset {self.i}")
                key = key_match.group(0)
                self.i += len(key)
            self._skip()
            if self.i >= self.n or self.text[self.i] != ":":
                raise GenerationError(f"expected colon after object key at offset {self.i}")
            self.i += 1
            result[key] = self._value()
            self._skip()
            if self.i < self.n and self.text[self.i] == ",":
                self.i += 1
                self._skip()
            elif self.i < self.n and self.text[self.i] != "}":
                raise GenerationError(f"expected comma in object at offset {self.i}")
        if self.i >= self.n:
            raise GenerationError("unterminated JavaScript object")
        self.i += 1
        return result


def _const_expressions(text: str) -> dict[str, tuple[int, int, str]]:
    """Return literal expression slices for exported constants."""
    result: dict[str, tuple[int, int, str]] = {}
    declaration = re.compile(r"export\s+const\s+([A-Za-z_$][\w$]*)\s*(?:.*?)=\s*", re.DOTALL)
    for match in declaration.finditer(text):
        name = match.group(1)
        start = match.end()
        index = start
        depth = 0
        quote: str | None = None
        while index < len(text):
            char = text[index]
            if quote:
                if char == "\\":
                    index += 2
                    continue
                if char == quote:
                    quote = None
            else:
                if char in "'\"`":
                    quote = char
                elif char in "[{(":
                    depth += 1
                elif char in "]})":
                    depth -= 1
                elif char == ";" and depth == 0:
                    break
            index += 1
        expression = text[start:index].strip()
        result[name] = (start, index, expression)
    return result


def _literal_values(text: str) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for name, (_, _, expression) in _const_expressions(text).items():
        if expression.startswith(("[", "{")):
            result[name] = _JSParser(expression).parse()
    return result


